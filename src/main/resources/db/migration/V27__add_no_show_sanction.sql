-- 노쇼 제재. 노쇼 1번마다 누적 횟수가 1 늘고, 노쇼가 난 방의 약속 시간부터 (누적 횟수 × 24시간) 동안 방 만들기·참여를 막는다.
-- 노쇼 없이 30일이 지날 때마다 누적 횟수가 1 줄어든다 - 줄어든 값은 저장하지 않고 읽거나 바꿀 때 계산한다(스케줄러 없음)
--   no_show_count            : 마지막으로 저장한 누적 횟수. 실제 횟수는 no_show_count_updated_at 에서 지난 30일 수만큼 뺀 값이다
--   no_show_count_updated_at : no_show_count 를 마지막으로 바꾼 시각(노쇼 기록·이의 인정). 감소 계산의 기준. 노쇼가 없었으면 NULL
--   restricted_until         : 이 시각까지 방 만들기·참여 불가. NULL 이면 제한 없음. 운영자가 이의를 받아들이면 NULL 로 풀린다
ALTER TABLE users
    ADD COLUMN no_show_count integer NOT NULL DEFAULT 0,
    ADD COLUMN no_show_count_updated_at timestamp(6) with time zone,
    ADD COLUMN restricted_until timestamp(6) with time zone;

-- 노쇼 이의 신청. 노쇼로 기록된 멤버가 앱에서 방마다 한 번 낸다. 운영자가 받아들이면(ACCEPTED) 그 노쇼가 무효로 돌아가고
-- (user_match_room.no_show_voided_at) 누적 횟수가 1 줄며 지금 걸린 제한이 풀린다. 거절하면(REJECTED) 그대로 둔다
CREATE TABLE no_show_objection (
    id bigint generated by default as identity,
    user_id bigint not null,
    match_id bigint not null,
    reason varchar(500) not null,
    status varchar(20) not null check ((status in ('PENDING','ACCEPTED','REJECTED'))),
    created_at timestamp(6) with time zone not null,
    resolved_at timestamp(6) with time zone,
    primary key (id)
);

-- 한 사람이 한 방에 한 번만 - 동시에 두 번 눌러도 하나만 남는다. 내 노쇼 기록 조회의 (user_id, match_id) 조인도 이 인덱스를 탄다
ALTER TABLE no_show_objection ADD CONSTRAINT uk_no_show_objection_user_match UNIQUE (user_id, match_id);
ALTER TABLE no_show_objection ADD CONSTRAINT fk_no_show_objection_match_room FOREIGN KEY (match_id) REFERENCES match_room (id);
-- 운영자 목록: 상태별 오래된 순
CREATE INDEX idx_no_show_objection_status_created_at ON no_show_objection (status, created_at, id);
