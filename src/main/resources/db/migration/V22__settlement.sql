CREATE TABLE settlement (
    id bigint generated by default as identity,
    taxi_driver_id bigint not null,
    period_start timestamp(6) with time zone not null,
    period_end timestamp(6) with time zone not null,
    amount integer not null,
    status varchar(255) not null check ((status in ('CONFIRMED','HOLD','PAID','FAILED'))),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    primary key (id)
);

ALTER TABLE settlement ADD CONSTRAINT uk_settlement_driver_period UNIQUE (taxi_driver_id, period_start);
CREATE INDEX idx_settlement_status_id ON settlement (status, id);

CREATE TABLE settlement_ledger (
    id bigint generated by default as identity,
    taxi_driver_id bigint not null,
    settlement_id bigint,
    match_id bigint not null,
    settlement_amount integer not null,
    total_fare integer not null,
    platform_promotion integer not null,
    occurred_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    primary key (id)
);
ALTER TABLE settlement_ledger ADD CONSTRAINT uk_settlement_ledger_match UNIQUE (match_id);
ALTER TABLE settlement_ledger ADD CONSTRAINT fk_settlement_ledger_settlement FOREIGN KEY (settlement_id) REFERENCES settlement (id);
CREATE INDEX idx_settlement_ledger_settlement ON settlement_ledger (settlement_id);
CREATE INDEX idx_settlement_ledger_unsettled ON settlement_ledger (taxi_driver_id, occurred_at) WHERE settlement_id IS NULL;

CREATE TABLE payout (
    id bigint generated by default as identity,
    settlement_id bigint not null,
    amount integer not null,
    status varchar(255) not null check ((status in ('REQUESTED','SUCCEED','FAILED','UNKNOWN'))),
    pg_id varchar(255),
    bank_code varchar(255) not null,
    account_number varchar(255) not null,
    account_holder varchar(255) not null,
    fail_reason varchar(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    primary key (id)
);
ALTER TABLE payout ADD CONSTRAINT fk_payout_settlement FOREIGN KEY (settlement_id) REFERENCES settlement (id);
CREATE UNIQUE INDEX uk_payout_settlement_active ON payout (settlement_id) WHERE status IN ('REQUESTED','UNKNOWN','SUCCEED');
CREATE INDEX idx_payout_settlement ON payout (settlement_id, id);
CREATE INDEX idx_payout_status_created_at ON payout (status, created_at);
