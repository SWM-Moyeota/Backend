-- 사전결제 검증 및 기존 결제 엔티티가 사용하는 테이블.
-- PG 거래 번호(pg_tx_id)와 내부 결제 기본키(id)를 구분한다.
CREATE TABLE payment_group (
    id bigint generated by default as identity primary key,
    match_id bigint,
    taxi_driver_id bigint,
    passenger_count integer,
    status varchar(255) check (status in ('PENDING', 'PARTIALLY_FAILED', 'COMPLETED', 'CANCELLED')),
    created_at timestamp(6),
    updated_at timestamp(6)
);

CREATE INDEX idx_payment_group_match_id ON payment_group (match_id);

CREATE TABLE payment (
    id bigint generated by default as identity primary key,
    pg_tx_id varchar(255),
    user_id bigint,
    payment_group_id bigint,
    payment_method_id bigint,
    amount integer,
    status varchar(255) check (status in ('PENDING', 'PAID', 'FAILED', 'CANCELED')),
    type varchar(255) check (type in ('VERIFICATION', 'MAIN')),
    order_name varchar(255),
    currency varchar(255) check (currency in ('KRW', 'USD', 'JPY')),
    fail_code varchar(255),
    created_at timestamp(6),
    updated_at timestamp(6)
);

CREATE INDEX idx_payment_group_id ON payment (payment_group_id);
CREATE INDEX idx_payment_user_id ON payment (user_id);

CREATE TABLE payment_log (
    id bigint generated by default as identity primary key,
    payment_id bigint,
    amount integer,
    status varchar(255) check (status in ('PENDING', 'PAID', 'FAILED', 'CANCELED')),
    type varchar(255) check (type in ('VERIFICATION', 'MAIN')),
    fail_code varchar(255),
    created_at timestamp(6),
    updated_at timestamp(6)
);

CREATE INDEX idx_payment_log_payment_id ON payment_log (payment_id);

CREATE TABLE payment_cancel (
    payment_id bigint primary key,
    cancel_at timestamp(6),
    cancel_reason varchar(255),
    created_at timestamp(6),
    updated_at timestamp(6)
);

CREATE TABLE payment_settlement (
    payment_group_id bigint primary key,
    total_fare integer,
    fare integer,
    remaining_balance integer,
    platform_charge integer,
    taxi_driver_id bigint,
    created_at timestamp(6)
);
