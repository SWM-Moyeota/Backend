CREATE TABLE driver_payout_account (
    id bigint generated by default as identity,
    taxi_driver_id bigint not null,
    business_type varchar(255) not null check ((business_type in ('INDIVIDUAL_BUSINESS','CORPORATE'))),
    bank_code varchar(255) not null,
    masked_account_number varchar(255) not null,
    account_holder varchar(255) not null,
    seller_id varchar(255),
    seller_status varchar(255) check ((seller_status in ('APPROVAL_REQUIRED','PARTIALLY_APPROVED','KYC_REQUIRED','APPROVED'))),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    primary key (id)
);

ALTER TABLE driver_payout_account ADD CONSTRAINT uk_driver_payout_account_driver UNIQUE (taxi_driver_id);
ALTER TABLE driver_payout_account ADD CONSTRAINT uk_driver_payout_account_seller UNIQUE (seller_id);
