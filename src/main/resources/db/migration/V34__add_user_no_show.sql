-- 노쇼를 건마다 남긴다. 노쇼 1건은 그 방의 약속 시간부터 30일 동안만 센다 - 지금 노쇼 횟수는
-- voided_at IS NULL AND meeting_at > now() - 30일 인 행 수다. 제한 끝 시각은 그대로 users.restricted_until 에 둔다
--   match_id   : 노쇼가 난 방. match_room 은 matching 모듈 테이블이라 FK 를 걸지 않는다
--   meeting_at : 그 방의 약속 시간(match_room.departure_at)을 기록할 때 옮겨 둔다
--   voided_at  : 운영자가 이의를 받아들여 무효로 돌린 시각. 채워져 있으면 세지 않는다
--   created_at : 노쇼로 기록한 시각
-- users FK 도 걸지 않는다 - 다른 테이블처럼 user_id 만 둔다. 탈퇴는 users 행을 남기는 soft delete 다
-- users.no_show_count·no_show_count_updated_at(V27)은 더 쓰지 않는다. 다음 릴리스에서 지운다
CREATE TABLE user_no_show (
    id bigint generated by default as identity,
    user_id bigint not null,
    match_id bigint not null,
    meeting_at timestamp(6) with time zone not null,
    voided_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    primary key (id)
);

-- 한 사람이 한 방에서 노쇼 한 건 - 같은 노쇼를 두 번 기록해도 두 번 세지 않는다
ALTER TABLE user_no_show ADD CONSTRAINT uk_user_no_show_user_match UNIQUE (user_id, match_id);
-- 지금 노쇼 횟수: 사용자의 약속 시간이 30일 안인 행
CREATE INDEX idx_user_no_show_user_meeting_at ON user_no_show (user_id, meeting_at);

-- 지금까지의 노쇼를 옮긴다(노쇼 기능은 dev 에만 나갔다). 노쇼는 약속이 정해진 방에서만 나와 departure_at 이 비어 있지 않다
INSERT INTO user_no_show (user_id, match_id, meeting_at, voided_at, created_at)
SELECT m.user_id, m.match_id, r.departure_at, m.no_show_voided_at, m.no_show_at
FROM user_match_room m
JOIN match_room r ON r.id = m.match_id
WHERE m.no_show_at IS NOT NULL;
