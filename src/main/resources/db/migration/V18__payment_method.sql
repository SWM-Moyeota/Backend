-- V18: 카드 결제수단 (포트원 빌링키). ERD 의 payment_method / card

CREATE TABLE payment_method (
    payment_method_id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    user_id bigint not null,
    billing_key varchar(255) not null unique,
    type varchar(255) not null check ((type in ('CARD'))),
    primary key (payment_method_id)
);

CREATE INDEX idx_payment_method_user_id ON payment_method (user_id);

-- 같은 사용자에 대한 동시 등록도 활성 수단은 하나만 허용한다.
CREATE UNIQUE INDEX uq_payment_method_active_user ON payment_method (user_id) WHERE deleted_at IS NULL;

CREATE TABLE card (
    payment_method_id bigint not null,
    name varchar(255),
    number varchar(255),
    brand varchar(255),
    primary key (payment_method_id)
);

ALTER TABLE IF EXISTS card ADD CONSTRAINT fk_card_payment_method FOREIGN KEY (payment_method_id) REFERENCES payment_method (payment_method_id);
