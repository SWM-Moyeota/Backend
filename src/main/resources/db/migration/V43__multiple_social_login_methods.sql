-- 기존 소셜 계정과 회원 번호를 보존하면서 복수 로그인 수단을 허용한다.
ALTER TABLE social_user ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE social_user DROP CONSTRAINT social_user_pkey;
ALTER TABLE social_user ADD PRIMARY KEY (id);
ALTER TABLE social_user ADD CONSTRAINT uk_social_user_user_type UNIQUE(user_id, social_type);
ALTER TABLE social_user DROP CONSTRAINT social_user_social_type_check;
ALTER TABLE social_user ADD CONSTRAINT social_user_social_type_check CHECK (social_type IN ('KAKAO','GOOGLE','NAVER','APPLE'));
ALTER TABLE social_user ADD COLUMN status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','REVOKED'));

-- 일회성 인증 요청 및 연결 재인증. 원문 토큰 대신 해시를 저장한다.
CREATE TABLE social_proof (
 token_hash varchar(64) PRIMARY KEY, purpose varchar(30) NOT NULL, user_id bigint,
 proof_value varchar(255) NOT NULL, expires_at timestamptz NOT NULL
);
CREATE INDEX ix_social_proof_expiry ON social_proof(expires_at);
-- 가입 중단·탈퇴 후에도 철회를 끝낼 수 있도록 회원 FK를 두지 않는다.
CREATE TABLE apple_credential (
 id uuid PRIMARY KEY, subject varchar(255) NOT NULL, client_id varchar(255) NOT NULL,
 token_cipher text NOT NULL, user_id bigint, signup_token varchar(255),
 expires_at timestamptz, verified_at timestamptz NOT NULL, state varchar(20) NOT NULL,
 attempts integer NOT NULL DEFAULT 0, retry_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_apple_credential_retry ON apple_credential(state,retry_at);
CREATE INDEX ix_apple_credential_user ON apple_credential(user_id);
CREATE TABLE apple_notification (event_id varchar(255) PRIMARY KEY, received_at timestamptz NOT NULL);
CREATE TABLE user_session_revocation (user_id bigint PRIMARY KEY, revoked_at timestamptz NOT NULL);

CREATE TABLE apple_grant_lock(subject varchar(255) PRIMARY KEY, revoked_at timestamptz);
